import { readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const projectRoot = process.cwd();
const apiRoot = path.join(projectRoot, "src", "app", "api");
const outputPath = path.join(
  projectRoot,
  "src",
  "server",
  "generated-api-routes.ts",
);

const METHODS = ["GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"];

function walk(dir) {
  const entries = readdirSync(dir);
  const files = [];

  for (const entry of entries) {
    const fullPath = path.join(dir, entry);
    const stats = statSync(fullPath);
    if (stats.isDirectory()) {
      files.push(...walk(fullPath));
      continue;
    }
    if (entry === "route.js" || entry === "route.ts") {
      files.push(fullPath);
    }
  }

  return files;
}

function toHonoPath(relativeRouteFile) {
  const withoutSuffix = relativeRouteFile.replace(/\/route\.(js|ts)$/, "");
  if (!withoutSuffix) {
    return "/";
  }

  const segments = withoutSuffix.split("/").filter(Boolean);
  const mapped = segments.map((segment) => {
    const param = segment.match(/^\[(\.{3})?([^\]]+)\]$/);
    if (!param) {
      return segment;
    }

    const [, dots, name] = param;
    if (dots === "...") {
      return `:${name}{.+}`;
    }
    return `:${name}`;
  });

  return `/${mapped.join("/")}`;
}

function scorePath(honoPath) {
  const segments = honoPath.split("/").filter(Boolean);
  let score = segments.length * 100;
  for (const segment of segments) {
    if (segment.includes("{.+}")) {
      score -= 20;
    } else if (segment.startsWith(":")) {
      score -= 10;
    } else {
      score += 5;
    }
  }
  return score;
}

function makeFile() {
  const routeFiles = walk(apiRoot)
    .map((file) => {
      const rel = path
        .relative(apiRoot, file)
        .split(path.sep)
        .join("/");
      const source = `../app/api/${rel}`;
      const relativeRoute = rel.replace(/\/route\.(js|ts)$/, "");
      const routePath = toHonoPath(rel);
      return {
        source,
        relativeRoute,
        routePath,
        score: scorePath(routePath),
      };
    })
    .sort((a, b) => b.score - a.score || a.relativeRoute.localeCompare(b.relativeRoute));

  const imports = routeFiles
    .map((route, index) => `import * as routeModule${index} from "${route.source}";`)
    .join("\n");

  const entries = routeFiles
    .map(
      (route, index) =>
        `  { path: "${route.routePath}", source: "${route.relativeRoute}", module: routeModule${index} as RouteModule },`,
    )
    .join("\n");

  return `/* eslint-disable */
// This file is generated by scripts/generate-api-routes.mjs.
// Do not edit manually.
${imports}

type Method = ${METHODS.map((m) => `"${m}"`).join(" | ")};
type RouteParams = Record<string, string>;
type RouteContext = { params: RouteParams };
type RouteHandler = (request: Request, context?: RouteContext) => Response | Promise<Response>;
type RouteModule = Partial<Record<Method, RouteHandler>>;

export type ApiRouteDefinition = {
  path: string;
  source: string;
  module: RouteModule;
};

export const apiRouteDefinitions: ApiRouteDefinition[] = [
${entries}
];
`;
}

writeFileSync(outputPath, makeFile(), "utf8");
console.log(`Generated ${path.relative(projectRoot, outputPath)}`);
